namespace TaskFlow.Domain.Common;

/// <summary>
/// Marker for aggregates that raise domain events. Events are collected by the
/// DbContext during SaveChanges and written to the transactional outbox in the
/// same database transaction as the state change.
/// </summary>
public interface IHasDomainEvents
{
    bool HasDomainEvents { get; }

    /// <summary>
    /// Materialises pending events. Evaluated after the entity has been inserted,
    /// so database-generated identifiers are available to the event payload.
    /// </summary>
    IReadOnlyList<IDomainEvent> CollectDomainEvents();

    void ClearDomainEvents();
}

public abstract class Entity : IHasDomainEvents
{
    // Events are stored as factories so that values generated by the database
    // (e.g. identity keys) are read when the event is collected, not when raised.
    private readonly List<Func<IDomainEvent>> _pendingEvents = [];

    public bool HasDomainEvents => _pendingEvents.Count > 0;

    protected void Raise(Func<IDomainEvent> eventFactory) => _pendingEvents.Add(eventFactory);

    public IReadOnlyList<IDomainEvent> CollectDomainEvents() => _pendingEvents.Select(f => f()).ToList();

    public void ClearDomainEvents() => _pendingEvents.Clear();
}
